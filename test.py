# Dummy Python Code - Basics
 
# 1. Variables and print

name = "Jayadevi"

age = 25

print(f"Hello {name}, you are {age} years old")
 
# 2. List and loop

fruits = ["apple", "banana", "mango"]

for fruit in fruits:

    print("Fruit:", fruit)
 
# 3. Function

def add(a, b):

    return a + b
 
print("Sum:", add(10, 20))
 
# 4. If-else

score = 75

if score >= 90:

    print("Grade A")

elif score >= 60:

    print("Grade B")

else:

    print("Grade C")
 
# 5. Dictionary

person = {"name": "Ravi", "city": "Chennai"}

print(person["name"], "lives in", person["city"])
 
